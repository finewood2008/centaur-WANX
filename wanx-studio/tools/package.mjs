import{build}from'esbuild';
import{mkdir,copyFile,writeFile,readFile,cp,rm}from'node:fs/promises';
import path from'node:path';
import{fileURLToPath}from'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));
const version=JSON.parse(await readFile(path.join(root,'package.json'),'utf8')).version;
const runtime=path.join(root,'dist/runtime'),studio=path.join(root,'release/wanx-studio-'+version);
await mkdir(path.join(studio,'assets'),{recursive:true});
await copyFile(path.join(root,'ui/assets/centaurai-mark.png'),path.join(studio,'assets/centaurai-mark.png'));
await mkdir(runtime,{recursive:true});await mkdir(path.join(studio,'shell'),{recursive:true});
for(const file of ['runtime-main.cjs','runtime-preload.cjs'])await build({entryPoints:[path.join(root,'shell',file)],bundle:true,platform:'node',format:'cjs',outfile:path.join(runtime,file),external:['electron'],logLevel:'silent'});
await build({entryPoints:[path.join(root,'shell/runtime-renderer.mjs')],bundle:true,platform:'browser',format:'iife',outfile:path.join(runtime,'runtime-renderer.js'),logLevel:'silent'});
await copyFile(path.join(root,'shell/runtime.html'),path.join(runtime,'runtime.html'));
await build({entryPoints:[path.join(root,'shell/main.cjs')],bundle:true,platform:'node',format:'cjs',outfile:path.join(studio,'shell/main.cjs'),external:['electron'],logLevel:'silent'});
await copyFile(path.join(root,'shell/preload.cjs'),path.join(studio,'shell/preload.cjs'));
await rm(path.join(studio,'ui'),{recursive:true,force:true});
await cp(path.join(root,'dist/ui'),path.join(studio,'ui'),{recursive:true});
await writeFile(path.join(studio,'application.manifest.json'),JSON.stringify({applicationId:'ai.wanx.studio',name:'半人马AI-万象Builder',version,protocolVersion:1,runtime:'electron',launchMode:'shared',entrypoint:'shell/main.cjs',description:'持续沟通、试用和改进自己的万象应用。'},null,2));
console.log(JSON.stringify({studio,runtime}));
