import test from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import net from "node:net";
import { once } from "node:events";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import readline from "node:readline";
import { createSpaceLinkBridge } from "../shell/space-links.mjs";
import { createDashboardGateway } from "../octop/gateway.mjs";
import { callTool, spaceRequest } from "../shell/space-links-mcp.mjs";

const waitFor = async predicate => { for (const end=Date.now()+30000;Date.now()<end;) { if(await predicate())return;await new Promise(r=>setTimeout(r,30)); }throw new Error("Timed out"); };
test("real HTTP service, client gateway, loopback link and stdio MCP: small-file CRUD and cleanup", { skip: !process.env.WANX_SPACE_PYTHON, timeout: 60000 }, async t => {
  const root = await mkdtemp(path.join(tmpdir(),"wanx-agent-links-"));
  t.after(()=>rm(root,{recursive:true,force:true}));
  const listener=net.createServer(); listener.listen(0,"127.0.0.1"); await once(listener,"listening"); const port=listener.address().port; await new Promise(r=>listener.close(r));
  const child=spawn(process.env.WANX_SPACE_PYTHON,[fileURLToPath(new URL("./support/personal-space-api.py",import.meta.url)),root,String(port)],{stdio:["ignore","ignore","pipe"]});
  let output="";child.stderr.on("data",data=>output+=data);
  t.after(async()=>{if(child.exitCode===null){child.kill("SIGTERM");await once(child,"exit");}});
  const base="http://127.0.0.1:"+port;
  await waitFor(async()=>{if(child.exitCode!==null)throw Error(output);try{return(await fetch(base+"/api/personal-space/overview")).ok;}catch{return false;}});
  const gateway=await createDashboardGateway({targetURL:base,session:{getToken:()=>"test-only",close(){}}}); t.after(()=>gateway.close());
  const client={snapshot:()=>({phase:"ready",account:{phase:"authenticated",accountId:"test-owner"},connection:{deviceId:"test-box"}}),subscribe:()=>()=>{},
    applicationConnection:async()=>({context(){},request:input=>gateway.request(input)})};
  let saved, changed=0;
  const bridge=await createSpaceLinkBridge({client,serviceURL:base,store:{load:async()=>saved,save:async value=>{saved=structuredClone(value);}},onChanged:()=>changed++});t.after(()=>bridge.close());
  const owner=async(route,method="GET",body)=>{const r=await fetch(base+"/api/personal-space"+route,{method,headers:{"content-type":"application/json"},body:body?JSON.stringify(body):undefined}); assert.ok(r.ok,await r.clone().text());return r.status===204?null:r.json();};
  const folder=await owner("/folders","POST",{name:"agent-link-small-sample"});
  const link=await bridge.manage("create",{root:folder.id});
  const descriptor=await(await fetch(link.url)).json();assert.equal(descriptor.resource?.id,folder.id,JSON.stringify(descriptor));
  let file=await callTool("space_write_text",{link:link.url,target:folder.id,name:"sample.txt",text:"Agent 测试\n".repeat(64)});
  const first=file;
  assert.equal((await callTool("space_read_text",{link:link.url,target:file.id})).digest,createHash("sha256").update("Agent 测试\n".repeat(64)).digest("hex"));
  file=await callTool("space_write_text",{link:link.url,target:file.id,expected:file.version,text:"updated"});
  assert.equal(file.id,first.id);
  await assert.rejects(callTool("space_write_text",{link:link.url,target:file.id,expected:first.version,text:"stale"}),/SPACE_VERSION_CONFLICT/);
  file=await spaceRequest({link:link.url,action:"restore-version",target:file.id,expected:file.version});
  assert.equal((await callTool("space_read_text",{link:link.url,target:file.id})).text,"Agent 测试\n".repeat(64));
  const nested=await spaceRequest({link:link.url,action:"mkdir",name:"nested"});
  file=await spaceRequest({link:link.url,action:"move",target:file.id,parent:nested.id,name:"moved.txt",expected:file.version});
  await spaceRequest({link:link.url,action:"trash",target:file.id,expected:file.version});
  file=await spaceRequest({link:link.url,action:"restore",target:file.id,expected:file.version+1});
  assert.equal((await spaceRequest({link:link.url,action:"list",target:nested.id})).items[0].id,file.id);
  // Exercise actual stdio framing in a separate agent-side process.
  const mcp=spawn(process.execPath,[fileURLToPath(new URL("../shell/space-links-mcp.mjs",import.meta.url))],{stdio:["pipe","pipe","pipe"]});
  t.after(()=>mcp.kill());
  const lines=readline.createInterface({input:mcp.stdout}), pending=new Map();
  lines.on("line",line=>{const msg=JSON.parse(line);pending.get(msg.id)?.(msg);pending.delete(msg.id);});
  let seq=0;
  const rpc=(method,params)=>new Promise(resolve=>{const id=++seq;pending.set(id,resolve);mcp.stdin.write(JSON.stringify({jsonrpc:"2.0",id,method,params})+"\n");});
  assert.equal((await rpc("initialize",{protocolVersion:"2025-11-25",capabilities:{},clientInfo:{name:"test",version:"1"}})).result.serverInfo.name,"wanx-space");
  assert.equal((await rpc("tools/list",{})).result.tools.length,3);
  const mcpWrite=await rpc("tools/call",{name:"space_write_text",arguments:{link:link.url,target:nested.id,name:"mcp.txt",text:"MCP result"}});
  assert.ok(!mcpWrite.result.isError,JSON.stringify(mcpWrite));
  const mcpFile=JSON.parse(mcpWrite.result.content[0].text);
  const mcpRead=await rpc("tools/call",{name:"space_read_text",arguments:{link:link.url,target:mcpFile.id}});
  assert.equal(JSON.parse(mcpRead.result.content[0].text).text,"MCP result");
  assert.ok(changed>=6);
  await bridge.manage("revoke",{id:link.id});
  await assert.rejects(spaceRequest({link:link.url,action:"describe"}),/SPACE_LINK_REVOKED/);
  await owner("/files/"+folder.id,"DELETE");await owner("/trash/"+folder.id,"DELETE");
  assert.equal((await owner("/files")).items.length,0);
  assert.equal((await owner("/overview")).filesBytes,0);
});
