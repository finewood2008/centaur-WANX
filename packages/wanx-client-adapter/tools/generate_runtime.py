"""Generate executable module bindings from the recorded WANX API snapshot."""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
BASELINE = HERE / "api-baseline"
SOURCE = HERE.parent / "github-publish/wanx-sdk/api-baseline"


def camel(value: str) -> str:
    parts = re.split(r"[-_]", value)
    return parts[0] + "".join(p.title() for p in parts[1:])


def main() -> None:
    BASELINE.mkdir(exist_ok=True)
    if not (BASELINE / "openapi.json").exists():
        for name in ("openapi.json", "operation-registry.json", "websocket-routes.json", "stream-review.json", "summary.json"):
            shutil.copyfile(SOURCE / name, BASELINE / name)
    spec = json.loads((BASELINE / "openapi.json").read_text())
    registry = json.loads((BASELINE / "operation-registry.json").read_text())
    stream_review = json.loads((BASELINE / "stream-review.json").read_text())
    stream_paths = {r["path"]: r["hint"] for r in stream_review}
    modules: dict[str, dict[str, str]] = {}
    entries = []
    for row in registry:
        op = spec["paths"][row["path"]][row["method"].lower()]
        name = camel(row["operationId"].split("_api_")[0])
        for tag in row["tags"]:
            module = modules.setdefault(camel(tag), {})
            assert name not in module, (tag, name)
            module[name] = row["operationId"]
        entries.append({**row, "alias": name,
                        "parameters": op.get("parameters", []),
                        "bodyRequired": op.get("requestBody", {}).get("required", False),
                        "contentTypes": list(op.get("requestBody", {}).get("content", {})),
                        "stream": stream_paths.get(row["path"], ""),
                        "summary": op.get("summary", "")})
    generated = HERE / "src/generated"
    generated.mkdir(parents=True, exist_ok=True)
    original_types = (HERE / "contracts/native-api.d.ts").read_text()
    (generated / "native-api.ts").write_text(
        "// Generated from api-baseline/openapi.json. See third-party/native-platform-NOTICE.\n"
        + original_types[original_types.index("export interface"):])
    (generated / "registry.ts").write_text(
        "// Generated by tools/generate_runtime.py.\n"
        + "export const operationRegistry = " + json.dumps(entries, ensure_ascii=False, indent=2) + " as const;\n"
        + "export const moduleRegistry = " + json.dumps(modules, ensure_ascii=False, indent=2) + " as const;\n")
    memory_rows = dict(re.findall(r'readonly (\w+): "([^"]+)";', (HERE / "contracts/memory-methods.d.ts").read_text()))
    (generated / "memory.ts").write_text("export const memoryMethods = " + json.dumps(memory_rows, indent=2) + " as const;\n")
    (HERE / "native/wanx/operations.json").write_text(json.dumps(entries, ensure_ascii=False, indent=2) + "\n")
    doc = ["# centaurai-wanx：完整 API 目录", "", "以下是固定 WANX 平台快照的实际客户端方法。每个方法提供普通调用、`.stream` 和 `.events`；SSE 使用标注的 SSE 路由，二进制/大响应使用 `.stream`。原生参数结构见随包 `api-baseline/openapi.json` 与 `NativeOperations` 类型。3项 internal-mcp 接口排除。", "", f"共 {len(modules)} 个模块、{len(entries)} 项 HTTP 操作。模块归属采用原生 tags；操作别名来自原生 operationId，不另建业务模块。", ""]
    for module, methods in sorted(modules.items()):
        doc += ["## " + module, "", "| SDK 方法 | 原生方法 / 路径 | 请求与流 |", "| --- | --- | --- |"]
        for alias, oid in methods.items():
            row = next(r for r in entries if r["operationId"] == oid)
            doc.append(f"| `sdk.modules.{module}.{alias}` | `{row['method']} {row['path']}` | {', '.join(row['contentTypes']) or 'parameters'}; {row['stream'] or 'HTTP'} |")
        doc.append("")
    (HERE / "docs/api-reference.md").write_text("\n".join(doc).rstrip() + "\n")
    print(json.dumps({"http_operations": len(entries), "modules": len(modules), "memory": len(memory_rows)}))


if __name__ == "__main__":
    main()
